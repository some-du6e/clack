// testdata/oracle.json is ECharts 6.1.0 itself (server-side rendering, the
// components Slack registers: echarts-core's wMSS) drawing Slack's options
// (k+pA and mhRP verbatim) for 29 written cases and 40 random ones, with
// text measured by Lato's advances (no kerning; a character outside
// Lato's first 0x2100 code points as 1em). The paths are the drawn
// commands (ECPolyline / ECPolygon's drawSegment) over ECharts' points.
// Generated by bk-data-viz's oracle (scratch: oracle.mjs, gentest.mjs).

type oracleFile struct {
	Tokens map[string]struct {
		Palette         []string `json:"palette"`
		AreaFillPalette []string `json:"areaFillPalette"`
	} `json:"tokens"`
	Cases []oracleCase `json:"cases"`
}

type oracleCase struct {
	Name    string          `json:"name"`
	Width   float64         `json:"width"`
	Height  float64         `json:"height"`
	Theme   string          `json:"theme"`
	Chart   json.RawMessage `json:"chart"`
	None    string          `json:"none"`
	Splits  [][3]float64    `json:"splits"`
	Axis    [][3]float64    `json:"axis"`
	Labels  [][5]any        `json:"labels"`
	Bars    [][5]any        `json:"bars"`
	Symbols [][4]any        `json:"symbols"`
	Sectors [][6]any        `json:"sectors"`
	Areas   []oraclePath    `json:"areas"`
	Lines   []oraclePath    `json:"lines"`
}

type oraclePath struct {
	Fill   string  `json:"fill"`
	Stroke string  `json:"stroke"`
	D      [][]any `json:"d"`
}

// latoMeasure is the oracle's measureText: Lato's advances at 13px.
func latoMeasure(t *testing.T) Measure {
	t.Helper()
	parse := func(b []byte) *sfnt.Font {
		f, err := sfnt.Parse(b)
		if err != nil {
			t.Fatal(err)
		}
		return f
	}
	reg, black := parse(fonts.Regular), parse(fonts.Black)
	var buf sfnt.Buffer
	return func(s string, w Weight) float64 {
		f := reg
		if w == Black {
			f = black
		}
		upem := float64(f.UnitsPerEm())
		width := 0.0
		for _, r := range s {
			gi, err := f.GlyphIndex(&buf, r)
			if err != nil || gi == 0 || r >= 0x2100 {
				width += 13
				continue
			}
			adv, err := f.GlyphAdvance(&buf, gi, fixed.Int26_6(f.UnitsPerEm())<<6, font.HintingNone)
			if err != nil {
				width += 13
				continue
			}
			width += float64(adv) / 64 * 13 / upem
		}
		return width
	}
}

func parseRGB(t *testing.T, s string) color.NRGBA {
	t.Helper()
	s = strings.TrimSuffix(strings.TrimPrefix(s, "rgb("), ")")
	p := strings.Split(s, ",")
	if len(p) != 3 {
		t.Fatalf("colour %q", s)
	}
	v := func(x string) uint8 { n, _ := strconv.Atoi(strings.TrimSpace(x)); return uint8(n) }
	return color.NRGBA{v(p[0]), v(p[1]), v(p[2]), 0xff}
}

func rgbOf(c color.NRGBA) string { return fmt.Sprintf("rgb(%d,%d,%d)", c.R, c.G, c.B) }

func num(v any) float64 {
	if f, ok := v.(float64); ok {
		return f
	}
	return math.NaN()
}

func near(a, b float64) bool {
	if math.IsNaN(a) || math.IsNaN(b) {
		return math.IsNaN(a) && math.IsNaN(b)
	}
	return math.Abs(a-b) <= 0.01
}

func TestLayoutMatchesECharts(t *testing.T) {
	raw, err := os.ReadFile("testdata/oracle.json")
	if err != nil {
		t.Fatal(err)
	}
	var f oracleFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	m := latoMeasure(t)
	for _, c := range f.Cases {
		t.Run(c.Name, func(t *testing.T) {
			tok := f.Tokens[c.Theme]
			var pal Palette
			for i := range pal.Series {
				pal.Series[i] = parseRGB(t, tok.Palette[i])
				pal.Area[i] = parseRGB(t, tok.AreaFillPalette[i])
			}
			d := ParseChart(c.Chart)
			spec := Build(&d, &pal)
			if c.None != "" {
				if spec != nil {
					t.Fatalf("Slack draws no chart (%s), got a %v option", c.None, spec.Kind)
				}
				return
			}
			if spec == nil {
				t.Fatalf("no option: err %v, type %q", d.Err, d.Type)
			}
			l := Lay(spec, c.Width, c.Height, m)
			if len(l.Splits) != len(c.Splits) {
				t.Errorf("split lines: got %d, want %d", len(l.Splits), len(c.Splits))
			}
			for i, w := range c.Splits {
				if i < len(l.Splits) {
					g := l.Splits[i]
					if !near(g.X1, w[0]) || !near(g.Y1, w[1]) || !near(g.X2, w[2]) {
						t.Errorf("split %d: got %.3f,%.3f-%.3f, want %v", i, g.X1, g.Y1, g.X2, w)
					}
				}
			}
			if len(c.Axis) == 1 && l.AxisLn != nil {
				g, w := l.AxisLn, c.Axis[0]
				if !near(g.X1, w[0]) || !near(g.Y1, w[1]) || !near(g.X2, w[2]) {
					t.Errorf("axis line: got %.3f,%.3f-%.3f, want %v", g.X1, g.Y1, g.X2, w)
				}
			} else if len(c.Axis) != 0 || l.AxisLn != nil && len(c.Axis) == 0 {
				t.Errorf("axis line: got %v, want %v", l.AxisLn, c.Axis)
			}
			if len(l.Labels) != len(c.Labels) {
				var got, want []string
				for _, g := range l.Labels {
					got = append(got, g.Text)
				}
				for _, w := range c.Labels {
					want = append(want, fmt.Sprint(w[0]))
				}
				t.Errorf("labels: got %q, want %q", got, want)
			}
			for i, w := range c.Labels {
				if i >= len(l.Labels) {
					break
				}
				g := l.Labels[i]
				al := map[Align]string{AlignLeft: "left", AlignCenter: "center", AlignRight: "right"}[g.Align]
				rot := 0.0
				if g.Rotate != 0 {
					rot = 1
				}
				if g.Text != w[0] || !near(g.X, num(w[1])) || !near(g.Y, num(w[2])) || al != w[3] || rot != num(w[4]) {
					t.Errorf("label %d: got %q @%.3f,%.3f %s rot %v, want %v", i, g.Text, g.X, g.Y, al, g.Rotate, w)
				}
			}
			if len(l.Bars) != len(c.Bars) {
				t.Errorf("bars: got %d, want %d", len(l.Bars), len(c.Bars))
			}
			for i, w := range c.Bars {
				if i >= len(l.Bars) {
					break
				}
				g := l.Bars[i]
				if !near(g.X, num(w[0])) || !near(g.Y, num(w[1])) || !near(g.W, num(w[2])) || !near(g.H, num(w[3])) || rgbOf(g.Color) != w[4] {
					t.Errorf("bar %d: got %.3f,%.3f %.3fx%.3f %s, want %v", i, g.X, g.Y, g.W, g.H, rgbOf(g.Color), w)
				}
			}
			if len(l.Symbols) != len(c.Symbols) {
				t.Errorf("symbols: got %d, want %d", len(l.Symbols), len(c.Symbols))
			}
			for i, w := range c.Symbols {
				if i >= len(l.Symbols) {
					break
				}
				g := l.Symbols[i]
				shown := 0.0
				if g.Shown {
					shown = 1
				}
				if !near(g.X, num(w[0])) || !near(g.Y, num(w[1])) || shown != num(w[2]) || rgbOf(g.Color) != w[3] {
					t.Errorf("symbol %d: got %.3f,%.3f shown %v %s, want %v", i, g.X, g.Y, g.Shown, rgbOf(g.Color), w)
				}
			}
			var sectors []SectorItem
			for _, s := range l.Sectors {
				if s.Index >= 0 || len(c.Sectors) > 0 {
					sectors = append(sectors, s)
				}
			}
			if len(sectors) != len(c.Sectors) {
				t.Errorf("sectors: got %d, want %d", len(sectors), len(c.Sectors))
			}
			for i, w := range c.Sectors {
				if i >= len(sectors) {
					break
				}
				g := sectors[i]
				fill := rgbOf(g.Fill)
				if g.Index < 0 {
					fill = "lightgray"
				}
				if !near(g.CX, num(w[0])) || !near(g.CY, num(w[1])) || !near(g.R, num(w[2])) || !near(g.Start, num(w[3])) || !near(g.End, num(w[4])) || fill != w[5] {
					t.Errorf("sector %d: got %.3f,%.3f r%.3f %.4f-%.4f %s, want %v", i, g.CX, g.CY, g.R, g.Start, g.End, fill, w)
				}
			}
			comparePaths(t, "area", l.Areas, c.Areas, true)
			comparePaths(t, "line", l.Lines, c.Lines, false)
		})
	}
}

func comparePaths(t *testing.T, what string, got []PathItem, want []oraclePath, fill bool) {
	t.Helper()
	if len(got) != len(want) {
		t.Errorf("%ss: got %d, want %d", what, len(got), len(want))
		return
	}
	for i, w := range want {
		g := got[i]
		col := w.Stroke
		if fill {
			col = w.Fill
		}
		if rgbOf(g.Color) != col {
			t.Errorf("%s %d: colour %s, want %s", what, i, rgbOf(g.Color), col)
		}
		// zrender closes an empty run too (a Z after a Z draws nothing)
		var wd [][]any
		for _, cmd := range w.D {
			if cmd[0] == "Z" && (len(wd) == 0 || wd[len(wd)-1][0] == "Z") {
				continue
			}
			wd = append(wd, cmd)
		}
		if len(g.Path) != len(wd) {
			t.Errorf("%s %d: %d commands, want %d", what, i, len(g.Path), len(wd))
			continue
		}
		for j, cmd := range wd {
			gc := g.Path[j]
			if string(gc.Op) != cmd[0] {
				t.Errorf("%s %d cmd %d: %c, want %v", what, i, j, gc.Op, cmd[0])
				break
			}
			for k := 1; k < len(cmd); k++ {
				if !near(gc.P[k-1], num(cmd[k])) {
					t.Errorf("%s %d cmd %d: %v, want %v", what, i, j, gc.P, cmd)
					break
				}
			}
		}
	}
}
